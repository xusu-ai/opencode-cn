function Question(props: ToolProps<typeof QuestionTool>) {
  const { theme } = useTheme()
  const i18n = useI18n()
  const t = i18n.t
  const count = createMemo(() => props.input.questions?.length ?? 0)

  function format(answer?: ReadonlyArray<string>) {
    if (!answer?.length) return t("tui.session.noAnswer")
    return answer.join(", ")
  }

  return (
    <Switch>
      <Match when={props.metadata.answers}>
        <BlockTool title={t("tui.session.questions")} part={props.part}>
          <box gap={1}>
            <For each={props.input.questions ?? []}>
              {(q, i) => (
                <box flexDirection="column">
                  <text fg={theme.textMuted}>{q.question}</text>
                  <text fg={theme.text}>{format(props.metadata.answers?.[i()])}</text>
                </box>
              )}
            </For>
          </box>
        </BlockTool>
      </Match>
      <Match when={true}>
        <InlineTool icon="→" pending={t("tui.session.askingQuestions")} complete={count()} part={props.part}>
          {t("tui.session.asked")}{count()} {count() !== 1 ? t("tui.session.questionsPlural") : t("tui.session.question")}
        </InlineTool>
      </Match>
    </Switch>
  )
}

